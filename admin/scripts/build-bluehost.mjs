// Packages the whole site for Bluehost: public website + admin + PHP back end.
//
//   npm run bluehost -- --email you@sinvesta.com.au
//
// Asks for the admin password (or reads ADMIN_PASSWORD), builds the admin,
// and writes ../dist/bluehost/public_html plus ../dist/sinvesta-bluehost.zip.
// Upload the zip in cPanel → File Manager → public_html → Extract.
import bcrypt from "bcryptjs";
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ADMIN = path.resolve(here, "..");
const REPO = path.resolve(ADMIN, "..");
const SITE = path.join(REPO, "SINVESTA MODERN FINAL WEB");
const PHP = path.join(REPO, "bluehost");
const DIST = path.join(REPO, "dist", "bluehost");
const OUT = path.join(DIST, "public_html");
const ZIP = path.join(REPO, "dist", "sinvesta-bluehost.zip");

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : undefined;
};

async function askHidden(question) {
  if (!process.stdin.isTTY) return "";
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
  rl._writeToOutput = (s) => rl.output.write(s.includes(question) ? s : "");
  const answer = await new Promise((res) => rl.question(question, res));
  rl.close();
  process.stdout.write("\n");
  return answer;
}

const copy = (from, to, skip = () => false) => fs.cpSync(from, to, { recursive: true, filter: (src) => !skip(path.basename(src)) });
const phpString = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

// ---- 1. admin credentials → config.php --------------------------------------
const existing = path.join(PHP, "config.local.php"); // optional, git-ignored
let configPhp;
const email = arg("email");
if (email) {
  const password = process.env.ADMIN_PASSWORD || (await askHidden("Admin password (min 12 characters): "));
  if (!password || password.length < 12) {
    console.error("Password must be at least 12 characters.");
    process.exit(1);
  }
  // bcryptjs writes $2b$; PHP's password_verify expects the identical $2y$ variant.
  const hash = bcrypt.hashSync(password, 12).replace(/^\$2b\$/, "$2y$");
  configPhp = `<?php\n// Generated by npm run bluehost on ${new Date().toISOString()}\nreturn [\n    'admin_email' => ${phpString(email.trim().toLowerCase())},\n    'admin_password_hash' => ${phpString(hash)},\n    'mail_from' => ${phpString(arg("mail-from") || "noreply@sinvesta.com.au")},\n    'data_dir' => '',\n];\n`;
  fs.writeFileSync(existing, configPhp); // remembered for the next build
} else if (fs.existsSync(existing)) {
  configPhp = fs.readFileSync(existing, "utf8");
  console.log("Using saved admin login from bluehost/config.local.php");
} else {
  console.error("First build: pass your admin email, e.g.  npm run bluehost -- --email you@sinvesta.com.au");
  process.exit(1);
}

// ---- 2. build the admin (static) ---------------------------------------------
console.log("Building admin…");
execSync("npx next build", { cwd: ADMIN, stdio: "inherit" });

// ---- 3. assemble public_html -------------------------------------------------
fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

copy(SITE, OUT, (n) => [".DS_Store", "README.md", "START-WEBSITE.bat"].includes(n));
copy(path.join(ADMIN, "out"), path.join(OUT, "admin"), (n) => n === "defaults.json");
copy(path.join(PHP, "_sinvesta"), path.join(OUT, "_sinvesta"), (n) => n === ".DS_Store" || n === "data");
fs.copyFileSync(path.join(ADMIN, "out", "defaults.json"), path.join(OUT, "_sinvesta", "defaults.json"));
fs.writeFileSync(path.join(OUT, "_sinvesta", "config.php"), configPhp);
fs.copyFileSync(path.join(PHP, "root.htaccess"), path.join(OUT, ".htaccess"));
fs.mkdirSync(path.join(OUT, "uploads"), { recursive: true });
fs.copyFileSync(path.join(PHP, "uploads.htaccess"), path.join(OUT, "uploads", ".htaccess"));

// ---- 4. zip ------------------------------------------------------------------
fs.rmSync(ZIP, { force: true });
execSync(`zip -qr -X "${ZIP}" .`, { cwd: OUT });
const mb = (fs.statSync(ZIP).size / 1e6).toFixed(1);
console.log(`\n✓ Ready: dist/sinvesta-bluehost.zip (${mb} MB)\n  Upload it to public_html in cPanel File Manager and choose Extract.\n`);
